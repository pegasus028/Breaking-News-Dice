// Builds apps-script/Code.gs from the shared browser files, so the backend and
// the demo run exactly the same engine.  Usage: node tools/build.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const parts = ['js/words.js', 'js/check.js', 'js/server.js'];
const head = '/* Breaking News Dice — Apps Script backend (GENERATED by tools/build.js — edit js/*.js, then rebuild).\n' +
  '   Needs a second script file, Roster.gs (private), defining ROSTER, TEACHER_PIN and SHEET_ID.\n' +
  '   Deploy: Deploy → New deployment → Web app → Execute as: Me → Who has access: Anyone. */\n\n';
const body = parts.map(p => '/* ===== ' + p + ' ===== */\n' + fs.readFileSync(path.join(root, p), 'utf8')).join('\n');
fs.mkdirSync(path.join(root, 'apps-script'), { recursive: true });
fs.writeFileSync(path.join(root, 'apps-script/Code.gs'), head + body);
console.log('apps-script/Code.gs', (head + body).length, 'chars');
